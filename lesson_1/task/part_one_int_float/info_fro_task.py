# =============================================
# Лекция: Функция input() в Python
# =============================================

# Функция input() позволяет получать данные от пользователя через консоль.
# Возвращает введенные данные в виде строки (str).

# 1. Базовое использование
# =============================================
print("1. Базовое использование:\n")

name = input("Введите ваше имя: ")  # Выводит подсказку и ждет ввода
print(f"Привет, {name}!\n")          # Привет, [имя]!

# 2. Преобразование типов
# =============================================
print("\n2. Преобразование типов:\n")

# input() возвращает строку, даже если введено число
age = input("Сколько вам лет? ")    # Например, ввод: 25
print(type(age))                     # <class 'str'>

# Явное преобразование в int/float
age_int = int(input("Сколько вам лет? "))  # Ввод должен быть числом!
price = float(input("Введите цену: "))
print(f"Через 5 лет вам будет {age_int + 5} лет.")
print(f"Цена с НДС: {price * 1.2}\n")