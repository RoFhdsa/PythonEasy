# =============================================
# Лекция 1: Типы данных. Неизменяемые (Immutable)
# =============================================

# Неизменяемые типы данных нельзя модифицировать после создания.
# При "изменении" создается новый объект в памяти.

# 1. Основные неизменяемые типы
# =============================================
print("1. Основные неизменяемые типы:\n")

# ----- int (целые числа) -----
a = 10
print(f"[int] Исходное значение: {a}, id: {id(a)}")
a += 5  # Создается новый объект
print(f"После изменения: {a}, id: {id(a)}\n")

# ----- float (числа с плавающей точкой) -----
b = 3.14
print(f"[float] Исходное значение: {b}, id: {id(b)}")
b *= 2  # Создается новый объект
print(f"После изменения: {b}, id: {id(b)}\n")

# ----- bool (логические значения) -----
flag = True
print(f"[bool] Значение: {flag}, id: {id(flag)}")
flag = False  # Просто переназначаем ссылку
print(f"После изменения: {flag}, id: {id(flag)}\n")

# ----- str (строки) -----
s = "Hello"
print(f"[str] Исходная строка: {s}, id: {id(s)}")
try:
    s[0] = "h"  # Попытка изменить символ
except TypeError as e:
    print(f"Ошибка: {e}")
s += " World"    # Создается новая строка
print(f"После изменения: {s}, id: {id(s)}\n")

# ----- tuple (кортежи) -----
t = (1, 2, 3)
print(f"[tuple] Исходный кортеж: {t}, id: {id(t)}")
try:
    t[0] = 10  # Попытка изменить элемент
except TypeError as e:
    print(f"Ошибка: {e}")
t += (4,)       # Создается новый кортеж
print(f"После изменения: {t}, id: {id(t)}\n")

# 2. Другие неизменяемые типы
# =============================================
print("\n2. Другие неизменяемые типы:\n")

# ----- bytes (байтовые строки) -----
b = b'abc'
print(f"[bytes] Исходные байты: {b}, id: {id(b)}")
try:
    b[0] = 100  # Попытка изменить байт
except TypeError as e:
    print(f"Ошибка: {e}\n")

# ----- frozenset (неизменяемое множество) -----
fs = frozenset([1, 2, 3])
print(f"[frozenset] Исходное множество: {fs}, id: {id(fs)}")
try:
    fs.add(4)  # Попытка добавить элемент
except AttributeError as e:
    print(f"Ошибка: {e}\n")

# 3. Особенности работы
# =============================================
print("\n3. Особенности работы:\n")

# Пример 1: "Изменение" строки через срезы
original = "Python"
print(f"Исходная строка: {original}, id: {id(original)}")
modified = original[:2] + "XX" + original[4:]
print(f"Модифицированная: {modified}, id: {id(modified)}")

# Пример 2: Неожиданное поведение с кортежами
t = (1, [2, 3])
print(f"\nКортеж с изменяемым элементом: {t}, id: {id(t)}")
t[1].append(4)  # Меняем вложенный список!
print(f"После изменения: {t}, id: {id(t)}")

# 4. Сравнение с изменяемыми типами
# =============================================
print("\n4. Сравнение с изменяемыми типами:\n")

# Списки (изменяемые) vs Кортежи (неизменяемые)
lst = [1, 2, 3]
tpl = (1, 2, 3)

print(f"Список до изменения: {lst}, id: {id(lst)}")
lst.append(4)
print(f"Список после изменения: {lst}, id: {id(lst)}")

print(f"\nКортеж до изменения: {tpl}, id: {id(tpl)}")
tpl += (4,)
print(f"Кортеж после изменения: {tpl}, id: {id(tpl)}")

# 5. Почему это важно?
# =============================================
print("\n\n5. Почему это важно?")
print("""
1. Безопасность данных: неизменяемые объекты потокобезопасны
2. Хешируемость: могут использоваться как ключи в словарях
3. Эффективность: некоторые оптимизации возможны только с immutable
4. Предсказуемость: данные не могут измениться неожиданно
""")

