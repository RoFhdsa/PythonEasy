# Циклы позволяют выполнять повторяющиеся действия.
# В Python есть два типа циклов: for и while.

# 1. Цикл for для итерации по коллекциям
# =============================================
print("\n1. Цикл for:")

# Пример 1: Итерация по списку
fruits = ["яблоко", "банан", "вишня"]
print("\nПример 1: Итерация по списку")
for fruit in fruits:
    print(f"Фрукт: {fruit}")

# Пример 2: range() с шагом 2
print("\nПример 2: Четные числа 0-10")
for num in range(0, 11, 2):
    print(num)

# 2. Цикл while с условием
# =============================================
print("\n\n2. Цикл while:")

# Пример 3: Обратный отсчет
print("\nПример 3: Обратный отсчет")
countdown = 3
while countdown > 0:
    print(f"Осталось: {countdown}")
    countdown -= 1
print("Старт!")

# 3. Управление циклами (break, continue, else)
# =============================================
print("\n\n3. Управление циклами:")

# Пример 4: break для выхода
print("\nПример 4: Прерывание цикла")
for num in range(10):
    if num == 5:
        break
    print(num)

# Пример 5: continue для пропуска
print("\nПример 5: Пропуск итерации")
for num in range(5):
    if num == 2:
        continue
    print(num)

# Пример 6: else после цикла
print("\nПример 6: Блок else")
for num in range(3):
    print(num)
else:
    print("Цикл завершен!")

# 4. Опасные моменты
# =============================================
print("\n\n4. Типичные ошибки:")

# Пример 7: Бесконечный цикл (раскомментируйте для демо)
# while True:
#     print("Бесконечность!")

# Пример 8: Изменение списка во время итерации
print("\nПример 8: Опасное удаление элементов")
numbers = [1, 2, 3, 4, 5]
print("Исходный список:", numbers)
for num in numbers:
    if num % 2 == 0:
        numbers.remove(num)
print("Результат:", numbers)  # [1, 3, 5]

# Решение: Итерируемся по копии
print("\nИсправленная версия:")
numbers = [1, 2, 3, 4, 5]
for num in numbers.copy():
    if num % 2 == 0:
        numbers.remove(num)
print("Результат:", numbers)  # [1, 3, 5]

# 5. Практические примеры
# =============================================
print("\n\n5. Практика:")

# Пример 9: Поиск простых чисел
print("\nПример 9: Простые числа до 20")
primes = []
for num in range(2, 21):
    for i in range(2, int(num**0.5)+1):
        if num % i == 0:
            break
    else:
        primes.append(num)
print("Простые числа:", primes)  # [2, 3, 5, 7, 11, 13, 17, 19]

# Пример 10: Генератор паролей
print("\nПример 10: Генератор символов")
import random
password = []
for _ in range(8):
    password.append(chr(random.randint(33, 126)))
print("Случайный пароль:", ''.join(password))

