# =============================================
# Лекция: Объявление переменных и функция print()
# =============================================

# 1. Объявление переменных
# =============================================
print("1. Объявление переменных:\n")

# Примеры создания переменных
age = 25                # Целое число (int)
name = "Анна"           # Строка (str)
price = 99.99           # Число с плавающей точкой (float)
is_student = True       # Логическое значение (bool)

# Вывод значений
print("age =", age)
print("name =", name)
print("price =", price)
print("is_student =", is_student, "\n")

# 2. Правила именования переменных
# =============================================
print("\n2. Правила именования переменных:\n")

# Допустимые имена
user_name = "Иван"
count2 = 10
_total = 100
print("Допустимые имена:", user_name, count2, _total)

# Недопустимые имена (раскомментировать для ошибки)
# 2count = 5    # SyntaxError
# class = "A"   # SyntaxError

# 3. Типы данных
# =============================================
print("\n3. Типы данных:\n")

# Автоматическое определение типа
print(f"Тип age: {type(age)}")        # <class 'int'>
print(f"Тип name: {type(name)}")      # <class 'str'>
print(f"Тип price: {type(price)}")    # <class 'float'>
print(f"Тип is_student: {type(is_student)}", "\n")  # <class 'bool'>

# 4. Функция print()
# =============================================
print("\n4. Функция print():\n")

# Базовое использование
print("Hello, World!")                 # Hello, World!
print(10, 20, 30)                      # 10 20 30
print("Имя:", name, "Возраст:", age)   # Имя: Анна Возраст: 25

# Параметры sep и end
print("\nС разделителем:")
print(10, 20, 30, sep='-')            # 10-20-30

print("\nС измененным окончанием:")
print("Привет", end=' ')
print("Мир!")                          # Привет Мир!

# 5. Форматирование строк
# =============================================
print("\n5. Форматирование строк:\n")

# F-строки (Python 3.6+)
print(f"{name} сейчас {age} лет.")     # Анна сейчас 25 лет.

# Метод format()
print("{} сейчас {} лет.".format(name, age))  # Анна сейчас 25 лет.

# 6. Практический пример
# =============================================
print("\n6. Практический пример:\n")

user_name = "Мария"
user_age = 30
user_city = "Москва"

# Вывод с f-строкой
print(f"Имя: {user_name}, Возраст: {user_age}, Город: {user_city}")
# Имя: Мария, Возраст: 30, Город: Москва

# 7. Итоги
# =============================================
print("\n7. Итоги:\n")

print('''1. Переменные создаются через присваивание.
2. Тип данных определяется автоматически.
3. print() поддерживает sep и end.
4. Используйте f-строки для форматирования.''')

