# =============================================
# Демонстрация погрешностей float
# =============================================

# Пример 1: Десятичные дроби в двоичной системе
# ---------------------------------------------
a = 0.1 + 0.2
print(f"0.1 + 0.2 = {a}")  # Ожидается 0.3, реально 0.30000000000000004

# Пример 2: Накопление погрешности
# ---------------------------------
total = 0.0
for _ in range(10):
    total += 0.1
print(f"Сумма 10 × 0.1 = {total}")  # 0.9999999999999999 вместо 1.0

# Пример 3: Потеря точности при операциях
# ----------------------------------------
result = (1.1 + 2.2) * 100
print(f"(1.1 + 2.2) × 100 = {result}")  # 330.00000000000006 вместо 330

# Пример 4: Опасность преобразования в int
# ----------------------------------------
number = 2.9999999999999999  # Почти 3.0
print(f"Исходное число: {number}")  # Python покажет 3.0 (из-за округления)
print(f"Преобразование в int: {int(number)}")  # 2 вместо ожидаемых 3

# Пример 5: Демонстрация с экспонентой
# -------------------------------------
big_num = 1e16
print(f"1e16 + 1 - 1e16 = {(big_num + 1) - big_num}")  # 0.0 вместо 1.0

# =============================================
# Почему это происходит?
# =============================================
"""
Числа с плавающей точкой (float) в Python используют двоичное представление,
что приводит к погрешностям при работе с десятичными дробями. 
Это ограничение аппаратной реализации IEEE 754.

Аналогия: 
Как 1/3 = 0.333333... нельзя точно представить в десятичной системе,
многие десятичные дроби нельзя точно представить в двоичной системе.
"""

# =============================================
# Как бороться с погрешностями?
# =============================================

# Способ 1: Округление
print(f"\nОкругление 2.9999999999999999: {round(2.9999999999999999)}")

# Способ 2: Использование модуля decimal
from decimal import Decimal

precise_num = Decimal('2.9999999999999999')
print(f"Точное представление: {precise_num}")

# Способ 3: Сравнение с допуском
x = 0.1 + 0.2
if abs(x - 0.3) < 1e-10:
    print("0.1 + 0.2 практически равно 0.3")