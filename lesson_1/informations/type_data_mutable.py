print("Изменение вложенных структур:")
mixed_tuple = (1, [2, 3])          # Кортеж с изменяемым элементом
print(f"Исходный кортеж: {mixed_tuple}, id: {id(mixed_tuple)}")
mixed_tuple[1].append(4)           # Модификация списка внутри кортежа
print(f"После изменений: {mixed_tuple}, id: {id(mixed_tuple)}\n")

# 5. Почему это важно?
# =============================================
print("\n5. Почему это важно?")
print("""
1. Экономия памяти: не создаются новые объекты при изменениях
2. Удобство работы: можно динамически модифицировать данные
3. Побочные эффекты: изменения влияют на все ссылки на объект
4. Не подходят для ключей словарей: требуют хешируемости
""")

# 6. Практические советы
# =============================================
