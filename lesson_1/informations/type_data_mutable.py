# =============================================
# Лекция 1: Типы данных. Изменяемые (Mutable)
# =============================================

# Изменяемые типы данных можно модифицировать после создания.
# Объект остается тем же в памяти, меняется его внутреннее состояние.

# 1. Основные изменяемые типы
# =============================================
print("1. Основные изменяемые типы:\n")

# ----- list (списки) -----
lst = [1, 2, 3]
print(f"[list] Исходный список: {lst}, id: {id(lst)}")
lst.append(4)      # Добавление элемента
lst[0] = 10        # Изменение элемента
print(f"После изменений: {lst}, id: {id(lst)}\n")

# ----- dict (словари) -----
dct = {"a": 1, "b": 2}
print(f"[dict] Исходный словарь: {dct}, id: {id(dct)}")
dct["c"] = 3       # Добавление новой пары
dct["a"] = 100      # Изменение значения
print(f"После изменений: {dct}, id: {id(dct)}\n")

# ----- set (множества) -----
st = {1, 2, 3}
print(f"[set] Исходное множество: {st}, id: {id(st)}")
st.add(4)           # Добавление элемента
st.remove(2)        # Удаление элемента
print(f"После изменений: {st}, id: {id(st)}\n")

# 2. Сравнение с неизменяемыми типами
# =============================================
print("\n4. Сравнение с неизменяемыми типами:\n")

# Список (изменяемый) vs Кортеж (неизменяемый)
