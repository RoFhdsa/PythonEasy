# =============================================
# Лекция: Функция input() в Python
# =============================================

# Функция input() позволяет получать данные от пользователя через консоль.
# Возвращает введенные данные в виде строки (str).

# 1. Базовое использование
# =============================================
print("1. Базовое использование:\n")

name = input("Введите ваше имя: ")  # Выводит подсказку и ждет ввода
print(f"Привет, {name}!\n")          # Привет, [имя]!

# 2. Преобразование типов
# =============================================
print("\n2. Преобразование типов:\n")

# input() возвращает строку, даже если введено число
age = input("Сколько вам лет? ")    # Например, ввод: 25
print(type(age))                     # <class 'str'>

# Явное преобразование в int/float
age_int = int(input("Сколько вам лет? "))  # Ввод должен быть числом!
price = float(input("Введите цену: "))
print(f"Через 5 лет вам будет {age_int + 5} лет.")
print(f"Цена с НДС: {price * 1.2}\n")

# 3. Обработка ошибок
# =============================================
print("\n3. Обработка ошибок:\n")

# Если ввести не число, возникнет ошибка при преобразовании
try:
    number = int(input("Введите число: "))
    print(f"Квадрат числа: {number ** 2}")
except ValueError:
    print("Ошибка! Нужно ввести целое число!\n")

# 4. Множественный ввод
# =============================================
print("\n4. Множественный ввод:\n")

# Через split() для разделения данных
data = input("Введите имя и возраст через пробел: ").split()  # Например: Анна 30
user_name, user_age = data[0], int(data[1])
print(f"Имя: {user_name}, Возраст через год: {user_age + 1}\n")

# 5. Практический пример
# =============================================
print("\n5. Практический пример:\n")

# Калькулятор суммы
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
print(f"Сумма: {a + b}")

# =============================================
# Итоги
# =============================================
print("\nИтоги:")
print('''
1. input() всегда возвращает строку.
2. Используйте int(), float() для преобразования.
3. Обрабатывайте исключения при вводе неверных данных.
4. split() помогает разделять введенные значения.''')

